import {
  addDoc,
  deleteDoc,
  doc,
  getDoc,
  getDocs,
  query,
  setDoc,
  updateDoc,
  where,
  type CollectionReference,
  type DocumentData,
  type DocumentReference,
  type WhereFilterOp,
} from '@react-native-firebase/firestore';
import { BaseEntity } from '../entities/BaseEntity';

// Base interface for entities that can be stored in Firestore
// More flexible than BaseEntity class for entities with custom timestamp handling
interface FirestoreEntity {
  id?: string;
  uid?: string;
}

function checkId<T extends FirestoreEntity>(object: T) {
  if (!object.uid && !object.id) {
    throw new Error('Item must have an id or uid attribute');
  }
}

function createId(collection: CollectionReference) {
  return doc(collection).id;
}

/**
 * Gets an item from a collection by id
 * @param collection
 * @param id
 */
async function get<T extends FirestoreEntity>(
  collection: CollectionReference,
  id: string,
): Promise<T> {
  const snapshot = await getDoc(doc(collection, id));
  return snapshot.data() as T;
}

/**
 * Gets items from a collection where attribute === value
 * If no items in the collection meet the criteria, this method will
 * return an empty array
 * @param collection
 * @param attribute
 * @param operator
 * @param value
 */
async function getByAttribute<T extends FirestoreEntity>(
  collection: CollectionReference,
  attribute: string,
  operator: WhereFilterOp,
  value: string | number | boolean | null,
): Promise<T[]> {
  const result = await getDocs(query(collection, where(attribute, operator, value)));
  return result.docs.length ? result.docs.map((snapshot) => snapshot.data() as T) : [];
}

/**
 * Updates an item in the given collection
 * @param collection
 * @param object
 */
async function update<T extends FirestoreEntity>(
  collection: CollectionReference,
  object: Partial<T>,
): Promise<void> {
  // firebase users have uids instead of ids
  checkId(object as FirestoreEntity);
  return updateDoc(
    doc(collection, (object.uid ? object.uid : object.id)!),
    object as DocumentData,
  );
}

async function deleteObject<T extends FirestoreEntity>(collection: CollectionReference, object: T) {
  checkId(object);
  // firebase users have uids instead of ids
  return deleteDoc(doc(collection, object.uid ? object.uid : object.id!));
}

/**
 * Creates a document in the given firestore collection. If given an id, it will create the document with that id,
 * otherwise one will be generated by firestore.
 * @param collection
 * @param object
 * @param id
 */
async function create<T extends FirestoreEntity>(
  collection: CollectionReference,
  object: T,
  id?: string,
): Promise<T> {
  if (!object.id) {
    object.id = id || doc(collection).id;
  }
  await setDoc(doc(collection, object.id), object as unknown as DocumentData);
  return object;
}

async function add<T extends FirestoreEntity>(
  collection: CollectionReference,
  object: T,
): Promise<DocumentReference<DocumentData>> {
  return addDoc(collection, object as unknown as DocumentData) as unknown as Promise<
    DocumentReference<DocumentData>
  >;
}

export { get, getByAttribute, update, deleteObject, create, add, createId };
