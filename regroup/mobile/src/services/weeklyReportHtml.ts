import { format, parseISO } from 'date-fns';
import type { Guest } from '../entities/Guest';
import type { WeekStats } from '../entities/WeekSummary';
import type { PhaseRule } from '../entities/Phase';

/**
 * The weekly compliance report's HTML, rendered to a PDF that staff share
 * outside the app. Residents can change their own name and staff can write the
 * phase and the week's figures, so every value is escaped and every figure is
 * coerced to a number: a non-number prints as NaN and fails its rule. The CSP
 * stops the renderer loading anything (images, fonts, scripts) from outside.
 */
export function buildWeeklyReportHtml(
  guest: Guest,
  stats: WeekStats,
  weekStart: string,
  phaseRules: PhaseRule,
): string {
  const meetingsRequired = Number(phaseRules.meetings ?? 0);
  const choresRequired = phaseRules.chore ? 1 : 0;
  const workRequired = Number(phaseRules.work ?? 0);
  const meetings = Number(stats.meetingsAttended);
  const chores = Number(stats.choresCompleted);
  const hours = Number(stats.hoursWorked);
  const medication = Number(stats.medicationTaken) > 0;
  const supporter = Number(stats.primarySupporterMet) > 0;

  const row = (activity: string, required: string, completed: string, pass: boolean) => `
        <tr>
          <td>${activity}</td>
          <td>${escapeHtml(required)}</td>
          <td>${escapeHtml(completed)}</td>
          <td class="${pass ? 'pass' : 'fail'}">
            ${pass ? 'PASS' : 'FAIL'}
          </td>
        </tr>`;

  return `
    <html>
    <head>
      <meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'">
      <style>
        body { font-family: Arial, sans-serif; padding: 20px; }
        h1 { color: #2c7be5; }
        table { width: 100%; border-collapse: collapse; margin-top: 20px; }
        th, td { border: 1px solid #ddd; padding: 8px 12px; text-align: left; }
        th { background: #f0f0f0; }
        .pass { color: green; }
        .fail { color: red; }
      </style>
    </head>
    <body>
      <h1>Weekly Compliance Report</h1>
      <p><strong>Resident:</strong> ${escapeHtml(residentName(guest))}</p>
      <p><strong>Week of:</strong> ${escapeHtml(format(parseISO(weekStart), 'MMMM d, yyyy'))}</p>
      <p><strong>Phase:</strong> ${escapeHtml(guest.phase)}</p>
      <table>
        <tr><th>Activity</th><th>Required</th><th>Completed</th><th>Status</th></tr>${row(
          'Meetings',
          String(meetingsRequired),
          String(meetings),
          meetings >= meetingsRequired,
        )}${row('Chores', String(choresRequired), String(chores), chores >= choresRequired)}${row(
          'Work Hours',
          String(workRequired),
          String(hours),
          hours >= workRequired,
        )}${row(
          'Medication',
          phaseRules.medications ? 'Required' : 'N/A',
          medication ? 'Yes' : 'No',
          !phaseRules.medications || medication,
        )}${row(
          'Sponsor Meeting',
          phaseRules.supporter ? 'Required' : 'N/A',
          supporter ? 'Yes' : 'No',
          !phaseRules.supporter || supporter,
        )}
      </table>
      <p style="margin-top: 30px; font-size: 12px; color: #999;">
        Generated by Regroup — ${escapeHtml(format(new Date(), 'MMMM d, yyyy h:mm a'))}
      </p>
    </body>
    </html>
  `;
}

const residentName = (guest: Guest) =>
  [guest.firstName, guest.lastName].filter((part) => part != null && part !== '').join(' ');

const HTML_ESCAPES: Record<string, string> = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;',
};

export function escapeHtml(value: unknown): string {
  return String(value ?? '').replace(/[&<>"']/g, (ch) => HTML_ESCAPES[ch]);
}
