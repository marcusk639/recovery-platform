/**
 * Writes functions/.env.<project> (gitignored), the non-secret config a
 * `firebase deploy --only functions` ships, from the reviewed list committed in
 * regroup/scripts/stripe-prices.env. A deploy from a clean worktree otherwise
 * ships no config: new functions get no price IDs and no CONNECT_BASE_URL.
 *
 *   npm run env:write -- --project phoenix-cleanhouse
 *
 * Only production has a committed source. Staging keeps its sandbox values
 * outside the repo, so it is refused here rather than handed production's.
 */
import * as fs from 'fs';
import * as path from 'path';

export const CONFIG_SOURCES: Record<string, string> = {
  'phoenix-cleanhouse': 'scripts/stripe-prices.env',
};

const TIER_PRICE_VARS = [
  'STRIPE_PRICE_TRAD_STARTER',
  'STRIPE_PRICE_TRAD_PROFESSIONAL',
  'STRIPE_PRICE_TRAD_ENTERPRISE',
  'STRIPE_PRICE_OXFORD_STANDARD',
  'STRIPE_PRICE_OXFORD_PLUS',
  'STRIPE_PRICE_OXFORD_NETWORK',
];

/** Every value a production deploy must carry (preflight-billing.js checks the same set and more). */
export const REQUIRED_KEYS = [
  ...TIER_PRICE_VARS,
  ...TIER_PRICE_VARS.map((v) => `${v}_ANNUAL`),
  'CONNECT_BASE_URL',
  'STRIPE_API_VERSION',
  'TIER_BILLING_ENABLED',
  'RECOVERY_API_BASE_URL',
];

/** Parses .env text as firebase's loader does: optional `export`, quotes, trailing ` # comment`. */
export function parseEnvText(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const raw of text.replace(/\r\n?/g, '\n').split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const m = line.match(/^(?:export\s+)?([\w.-]+)\s*=\s*(.*)$/);
    if (!m) continue;
    let val = m[2].trim();
    if (val[0] === '"' || val[0] === "'") {
      const end = val.indexOf(val[0], 1);
      val = end === -1 ? val.slice(1) : val.slice(1, end);
    } else {
      const hash = val.indexOf(' #');
      if (hash !== -1) val = val.slice(0, hash).trim();
    }
    out[m[1]] = val;
  }
  return out;
}

export function renderEnv(values: Record<string, string>, source: string): string {
  const lines = Object.entries(values).map(([k, v]) =>
    /^[\w./:@,-]*$/.test(v) ? `${k}=${v}` : `${k}=${JSON.stringify(v)}`,
  );
  return `# Generated by \`npm run env:write\` from ${source}. Edit that file, not this one.\n${lines.join('\n')}\n`;
}

function projectArg(argv: string[]): string | undefined {
  const i = argv.indexOf('--project');
  if (i !== -1) return argv[i + 1];
  return argv.find((a) => a.startsWith('--project='))?.slice('--project='.length);
}

export function main(
  argv: string[] = process.argv.slice(2),
  regroupDir = path.resolve(__dirname, '../../..'),
): string {
  const project = projectArg(argv);
  if (!project) throw new Error('usage: npm run env:write -- --project <firebase project id>');
  const source = CONFIG_SOURCES[project];
  if (!source) {
    throw new Error(
      `no committed config for ${project}: only ${Object.keys(CONFIG_SOURCES).join(', ')} has one. ` +
        `Write functions/.env.${project} by hand from that project's own values.`,
    );
  }
  const values = parseEnvText(fs.readFileSync(path.join(regroupDir, source), 'utf8'));
  const missing = REQUIRED_KEYS.filter((k) => !values[k] || !values[k].trim());
  if (missing.length)
    throw new Error(`${source} is missing required values: ${missing.join(', ')}`);
  const target = path.join(regroupDir, 'functions', `.env.${project}`);
  fs.writeFileSync(target, renderEnv(values, source));
  return target;
}

if (require.main === module) {
  try {
    const target = main();
    console.log(`wrote ${path.relative(process.cwd(), target)}`);
  } catch (err) {
    console.error((err as Error).message);
    process.exit(1);
  }
}
