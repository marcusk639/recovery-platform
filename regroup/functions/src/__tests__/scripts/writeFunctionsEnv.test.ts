import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';

import {
  CONFIG_SOURCES,
  main,
  parseEnvText,
  renderEnv,
  REQUIRED_KEYS,
} from '../../scripts/writeFunctionsEnv';

const committedSource = path.resolve(__dirname, '../../../../scripts/stripe-prices.env');

describe('writeFunctionsEnv', () => {
  let root: string;
  beforeEach(() => {
    root = fs.mkdtempSync(path.join(os.tmpdir(), 'regroup-env-'));
    fs.mkdirSync(path.join(root, 'scripts'));
    fs.mkdirSync(path.join(root, 'functions'));
  });
  afterEach(() => fs.rmSync(root, { recursive: true, force: true }));

  const source = (text: string) =>
    fs.writeFileSync(path.join(root, CONFIG_SOURCES['phoenix-cleanhouse']), text);
  const complete = () => REQUIRED_KEYS.map((k) => `${k}=value-${k}`).join('\n');

  it('parses the reviewed list the way firebase reads .env files', () => {
    expect(parseEnvText('# c\nA="quoted # kept"\nexport B=plain # trailing\n\nC=\n')).toEqual({
      A: 'quoted # kept',
      B: 'plain',
      C: '',
    });
  });

  it('writes functions/.env.<project> from the committed list for production', () => {
    source(`${complete()}\nEXTRA=1\n`);
    main(['--project', 'phoenix-cleanhouse'], root);
    const written = fs.readFileSync(path.join(root, 'functions/.env.phoenix-cleanhouse'), 'utf8');
    expect(parseEnvText(written)).toEqual({ ...parseEnvText(complete()), EXTRA: '1' });
    expect(written).toContain('Generated by `npm run env:write`');
  });

  it('refuses a project with no committed config, so staging values never come from production', () => {
    expect(() => main(['--project', 'regroup-e2e'], root)).toThrow(
      /no committed config for regroup-e2e/,
    );
  });

  it('refuses to write when a required value is missing or empty, naming it', () => {
    source(complete().replace('CONNECT_BASE_URL=value-CONNECT_BASE_URL', 'CONNECT_BASE_URL='));
    expect(() => main(['--project', 'phoenix-cleanhouse'], root)).toThrow(/CONNECT_BASE_URL/);
    expect(fs.existsSync(path.join(root, 'functions/.env.phoenix-cleanhouse'))).toBe(false);
  });

  it('requires a --project', () => {
    expect(() => main([], root)).toThrow(/--project/);
  });

  it('quotes values that need it and leaves plain ones bare', () => {
    expect(renderEnv({ A: 'plain', B: 'has space', C: '' }, 'src')).toContain(
      'A=plain\nB="has space"\nC=\n',
    );
  });

  // The real reviewed list must be complete, or a production deploy ships unset config.
  it('the committed scripts/stripe-prices.env has every required value', () => {
    const values = parseEnvText(fs.readFileSync(committedSource, 'utf8'));
    for (const key of REQUIRED_KEYS)
      expect([key, values[key] || '']).toEqual([key, expect.stringMatching(/\S/)]);
    expect(values.CONNECT_BASE_URL).toBe('https://regroup-app.com/connect');
  });
});
